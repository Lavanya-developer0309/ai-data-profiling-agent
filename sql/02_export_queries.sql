-- Export queries - run in Snowsight, then use the download button (CSV / TSV) above the results.
USE ROLE MIG_DEVELOPER;
USE WAREHOUSE MIG_WH;

-- 1. All files profiled, latest first
SELECT TABLE_NAME, SOURCE_FILE, ROW_COUNT, CHECKS_RUN, CHECKS_FAILED, ISSUES_FOUND, COLUMNS_WITH_ISSUES, RUN_AT, RUN_BY
FROM HC_MIGRATION_DB.PROFILING.PROFILE_RUN
ORDER BY RUN_AT DESC;

-- 2. Issues for one file (change the file name), worst first
SELECT TABLE_NAME, COLUMN_NAME, DATA_TYPE, MAX_LENGTH_RULE, ACTUAL_MIN_LENGTH, ACTUAL_MAX_LENGTH,
       CHECK_NAME, SEVERITY, FAILED_ROWS, FAILED_PCT, EXAMPLE_VALUES
FROM HC_MIGRATION_DB.PROFILING.V_PROFILE_RESULTS
WHERE SOURCE_FILE = 'SRC_MEMBER.txt' AND STATUS = 'FAIL'
ORDER BY DECODE(SEVERITY, 'High', 1, 'Medium', 2, 3), FAILED_ROWS DESC;

-- 3. Every check for one file, passed and failed
SELECT * FROM HC_MIGRATION_DB.PROFILING.V_PROFILE_RESULTS
WHERE SOURCE_FILE = 'SRC_MEMBER.txt'
ORDER BY COLUMN_POSITION, CHECK_NAME;

-- 4. The exact failing rows for one check (e.g. gender codes not in M, F, U)
SELECT TABLE_NAME, COLUMN_NAME, DATA_TYPE, CHECK_NAME, ROW_NO, KEY_COLUMN, KEY_VALUE, COLUMN_VALUE, VALUE_LENGTH
FROM HC_MIGRATION_DB.PROFILING.V_PROFILE_FAILED_ROWS
WHERE SOURCE_FILE = 'SRC_MEMBER.txt' AND COLUMN_NAME = 'GENDER_CODE'
ORDER BY ROW_NO;

-- 5. Column profile for one file
SELECT COLUMN_POSITION, COLUMN_NAME, DATA_TYPE, LOADED_AS, IS_REQUIRED, MIN_LENGTH_RULE, MAX_LENGTH_RULE,
       ROW_COUNT, NULL_COUNT, NULL_PCT, DISTINCT_COUNT, MIN_LENGTH, MAX_LENGTH, TOP_VALUES
FROM HC_MIGRATION_DB.PROFILING.PROFILE_COLUMN
WHERE SOURCE_FILE = 'SRC_MEMBER.txt'
ORDER BY COLUMN_POSITION;
